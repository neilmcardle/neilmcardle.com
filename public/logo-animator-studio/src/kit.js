async function buildKit({ size = 1080, fps = 60, framing = 'fit', sequence = true, onProgress = () => {} } = {}) {
  const values = { ...state.v }, n = logo.parts.length, name = logoName();
  if (values.duration * fps > 300) fps = 30;
  const frames = Math.max(2, Math.round(values.duration * fps));
  const frameOf = (k) => frameAt((k / frames) * values.duration, n, values);
  const canvas = document.createElement('canvas');
  const material = attach(canvas);
  if (!material) throw new Error('This browser cannot run the material renderer (WebGL 2 is needed).');
  await material.load(size >= 2160 && n <= 8 ? 2048 : 1024);
  const flat = document.createElement('canvas'), read = document.createElement('canvas');
  const ctx = flat.getContext('2d'), rtx = read.getContext('2d', { willReadFrequently: true });

  let pad = PAD / state.scale;
  if (framing === 'fit') {
    const S = 192, step = Math.max(1, Math.floor(frames / 90));
    canvas.width = canvas.height = read.width = read.height = S;
    let reach = 0;
    for (let k = 0; k < frames; k += step) {
      material.render(frameOf(k), values, PAD);
      rtx.clearRect(0, 0, S, S); rtx.drawImage(canvas, 0, 0);
      const px = rtx.getImageData(0, 0, S, S).data;
      for (let y = 0; y < S; y++) for (let x = 0; x < S; x++) if (px[(y * S + x) * 4 + 3] > 10) reach = Math.max(reach, Math.abs((x + 0.5) / S - 0.5), Math.abs((y + 0.5) / S - 0.5));
    }
    pad = PAD * clamp((reach + 0.03) * 2, 0.2, 1);
  }
  canvas.width = canvas.height = flat.width = flat.height = read.width = read.height = size;

  const avc = await supported(['avc1.640033', 'avc1.64002a', 'avc1.4d002a', 'avc1.42002a'].map((codec) => ({ codec, width: size, height: size, bitrate: size > 1080 ? 40e6 : 18e6, framerate: fps })));
  const vp9 = await supported(['vp09.00.51.08', 'vp09.00.41.08', 'vp09.00.40.08'].map((codec) => ({ codec, width: size, height: size, bitrate: size > 1080 ? 30e6 : 14e6, framerate: fps })));
  const mp4 = () => recorder(avc, new Mp4Muxer({ target: new Mp4Target(), video: { codec: 'avc', width: size, height: size }, fastStart: 'in-memory' }));
  const onBlack = avc && mp4(), onWhite = avc && mp4();
  const colour = vp9 && collector(vp9, size), alpha = vp9 && collector({ ...vp9, bitrate: vp9.bitrate / 3 }, size);
  const rgb = vp9 && new Uint8Array(size * size * 4), mono = vp9 && new Uint8Array(size * size * 1.5).fill(128);

  const files = {};
  for (let k = 0; k < frames; k++) {
    material.render(frameOf(k), values, pad);
    if (sequence) files[`frames/frame-${pad4(k + 1)}.png`] = [await bytes(await blobOf(canvas)), { level: 0 }];
    for (const [rec, bg] of [[onBlack, '#000'], [onWhite, '#fff']]) {
      if (!rec) continue;
      ctx.fillStyle = bg; ctx.fillRect(0, 0, size, size); ctx.drawImage(canvas, 0, 0);
      await rec.add(flat, k, fps);
    }
    if (vp9) {
      rtx.clearRect(0, 0, size, size); rtx.drawImage(canvas, 0, 0);
      const px = rtx.getImageData(0, 0, size, size).data;
      for (let i = 0; i < px.length; i += 4) {
        const a = px[i + 3];
        rgb[i] = px[i]; rgb[i + 1] = px[i + 1]; rgb[i + 2] = px[i + 2]; rgb[i + 3] = 255;
        mono[i >> 2] = a;
      }
      await colour.add(rgb, k, fps);
      await alpha.add(mono, k, fps, 'I420');
    }
    onProgress((k + 1) / (frames + 4), `Rendering frame ${k + 1} of ${frames}`);
  }
  onProgress(frames / (frames + 4), 'Finishing video');
  if (onBlack) { files['video/loop-on-black.mp4'] = [await onBlack.finish(), { level: 0 }]; files['video/loop-on-white.mp4'] = [await onWhite.finish(), { level: 0 }]; }
  let transparent = false;
  if (vp9) {
    const c = await colour.finish(), a = await alpha.finish();
    if (c.length === a.length && c.every((x, i) => x.type === a[i].type)) {
      const muxer = new WebmMuxer({ target: new WebmTarget(), video: { codec: 'V_VP9', width: size, height: size, frameRate: fps, alpha: true } });
      c.forEach((x, i) => muxer.addVideoChunkRaw(x.data, x.type, x.timestamp, x.meta, alphaBlock(a[i].data)));
      muxer.finalize();
      files['video/loop-alpha.webm'] = [new Uint8Array(muxer.target.buffer), { level: 0 }];
      transparent = true;
    }
  }

  onProgress((frames + 1) / (frames + 4), 'Rendering posters');
  const mid = frameAt(values.duration * 0.5, n, values);
  material.render(mid, values, pad);
  files['poster.png'] = [await bytes(await blobOf(canvas)), { level: 0 }];
  canvas.width = canvas.height = Math.min(4096, size * 2);
  material.render(mid, values, pad);
  files['poster@2x.png'] = [await bytes(await blobOf(canvas)), { level: 0 }];

  onProgress((frames + 2) / (frames + 4), 'Writing the live component and shader');
  files['live/logo-material.js'] = strToU8(await runtimeSource(values, partSources(1024), partSources(768, true)));
  files['live/index.html'] = strToU8(demoPage(name));
  const shaderNames = { QUAD_VS: 'quad.vert', PART_VS: 'part.vert', PART_FS: 'part.frag', BLUR_FS: 'blur.frag', SEED_FS: 'seed.frag', FLOOD_FS: 'flood.frag', HEIGHT_FS: 'height.frag', SLOPE_FS: 'slope.frag', GLASS_FS: 'glass.frag' };
  for (const key in shaderNames) files[`shader/${shaderNames[key]}`] = strToU8(`${SHADERS[key]}\n`);
  files['shader/uniforms.json'] = strToU8(JSON.stringify({ uPad: +pad.toFixed(3), ...Object.fromEntries(RINGS[3].params.map((p) => [`u${p.id[0].toUpperCase()}${p.id.slice(1)}`, values[p.id] / 100])) }, null, 2));
  if (!logo.raster) {
    const clean = logo.svg.cloneNode(true);
    clean.removeAttribute('aria-hidden');
    clean.querySelectorAll('[style]').forEach((e) => e.removeAttribute('style'));
    clean.querySelectorAll('[data-i]').forEach((e) => e.removeAttribute('data-i'));
    clean.setAttribute('xmlns', 'http://www.w3.org/2000/svg');
    clean.setAttribute('style', `color:${state.color}`);
    files['vector/logo.svg'] = strToU8(new XMLSerializer().serializeToString(clean));
    files['vector/animated.svg'] = strToU8(buildExportSVG(values));
  }
  files['settings.json'] = strToU8(JSON.stringify({ name, color: state.color, size, fps, frames, framing, values: { ...values, easing: EASES[values.easing].name }, peaks: Object.fromEntries(Object.keys(PEAK).map((id) => [id, +((state.at[id] / 360) * values.duration).toFixed(3)])) }, null, 2));
  files['README.md'] = strToU8(readme({ name, size, fps, frames, values, alpha: transparent, mp4: !!avc, vector: !logo.raster, framing, fill: Math.round(100 / pad), sequence }));

  onProgress((frames + 3) / (frames + 4), 'Zipping');
  await new Promise((r) => setTimeout(r, 30));
  const zip = zipSync(files);
  onProgress(1, 'Done');
  return { zip, files: Object.keys(files), name: `${slug(name)}-kit.zip`, alpha: transparent, mp4: !!avc, frames, fps, pad };
}

