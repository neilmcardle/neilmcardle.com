async function supported(configs) {
  if (typeof VideoEncoder === 'undefined') return null;
  for (const config of configs) {
    try { const r = await VideoEncoder.isConfigSupported(config); if (r.supported && (!config.alpha || r.config.alpha === config.alpha)) return config; } catch (e) { /* try the next one */ }
  }
  return null;
}
function recorder(config, muxer) {
  let failed = null;
  const encoder = new VideoEncoder({ output: (chunk, meta) => muxer.addVideoChunk(chunk, meta), error: (e) => { failed = e; } });
  encoder.configure(config);
  return {
    async add(source, k, fps) {
      if (failed) throw failed;
      const frame = new VideoFrame(source, { timestamp: Math.round((k * 1e6) / fps), duration: Math.round(1e6 / fps) });
      encoder.encode(frame, { keyFrame: k % fps === 0 });
      frame.close();
      while (encoder.encodeQueueSize > 6) await new Promise((r) => setTimeout(r, 4));
    },
    async finish() { await encoder.flush(); encoder.close(); if (failed) throw failed; muxer.finalize(); return new Uint8Array(muxer.target.buffer); },
  };
}
function collector(config, size) {
  let failed = null;
  const chunks = [];
  const encoder = new VideoEncoder({
    output: (chunk, meta) => { const data = new Uint8Array(chunk.byteLength); chunk.copyTo(data); chunks.push({ data, type: chunk.type, timestamp: chunk.timestamp, meta }); },
    error: (e) => { failed = e; },
  });
  encoder.configure(config);
  return {
    async add(pixels, k, fps, format = 'RGBA') {
      if (failed) throw failed;
      const frame = new VideoFrame(pixels, { format, codedWidth: size, codedHeight: size, timestamp: Math.round((k * 1e6) / fps), duration: Math.round(1e6 / fps) });
      encoder.encode(frame, { keyFrame: k % fps === 0 });
      frame.close();
      while (encoder.encodeQueueSize > 6) await new Promise((r) => setTimeout(r, 4));
    },
    async finish() { await encoder.flush(); encoder.close(); if (failed) throw failed; return chunks.sort((x, y) => x.timestamp - y.timestamp); },
  };
}
const vint = (n) => (n < 0x7f ? [0x80 | n] : n < 0x3fff ? [0x40 | (n >> 8), n & 255] : n < 0x1fffff ? [0x20 | (n >> 16), (n >> 8) & 255, n & 255] : [0x10 | (n >> 24), (n >> 16) & 255, (n >> 8) & 255, n & 255]);
function alphaBlock(data) {
  const inner = [0xee, 0x81, 0x01, 0xa5, ...vint(data.length)], head = [0xa6, ...vint(inner.length + data.length), ...inner];
  const out = new Uint8Array(head.length + data.length);
  out.set(head); out.set(data, head.length);
  return out;
}

