export default function ProductBadge({
  badge,
  size = 40,
}: {
  badge: BadgeKey;
  size?: number;
}) {
  const uid = useId().replace(/:/g, "");
  const id = `badge-${badge}-${uid}`;
  const shadow = SHADOWS[badge];

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 63 63"
      fill="none"
      aria-hidden="true"
    >
      <MarkPlate id={id} />

      {badge === "makeebook" && (
        <g filter={`url(#${id}-drop)`}>
          <path d={MAKEEBOOK_TOP} fill="#FBF9F3" />
          <path d={MAKEEBOOK_BOTTOM} fill="#FBF9F3" />
        </g>
      )}

      {badge === "coverly" && (
        <g filter={`url(#${id}-drop)`}>
          <path d={COVERLY_MARK} fill="#FBF9F3" />
        </g>
      )}

      {badge === "spark" && (
        <g filter={`url(#${id}-drop)`}>
          <path d={SPARK_MARK} fill="#FEFEFE" />
        </g>
      )}

      {badge === "doodlewire" && (
        <g filter={`url(#${id}-drop)`}>
          <path
            fillRule="evenodd"
            clipRule="evenodd"
            d={DOODLEWIRE_TOP}
            fill="#FBF9F3"
          />
          <path d={DOODLEWIRE_BOTTOM} fill="#FBF9F3" />
        </g>
      )}

      <defs>
        <MarkEdge id={id} />
        <Shadow id={`${id}-drop`} {...shadow} />
      </defs>
    </svg>
  );
}
