export default function ProductBadge({
  badge,
  size = 40,
}: {
  badge: BadgeKey;
  size?: number;
}) {
  const uid = useId().replace(/:/g, "");
  const id = `badge-${badge}-${uid}`;

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 62 62"
      fill="none"
      aria-hidden="true"
    >
      <Plate id={id} />

      {badge === "makeebook" && (
        <g filter={`url(#${id}-drop)`}>
          <path d={MAKEEBOOK_TOP} fill="#FBF9F3" />
          <path d={MAKEEBOOK_BOTTOM} fill="#FBF9F3" />
        </g>
      )}

      {badge === "coverly" && (
        <g filter={`url(#${id}-drop)`}>
          <path d={COVERLY_MARK} fill="#FBF9F3" />
        </g>
      )}

      {badge === "spark" && (
        <g filter={`url(#${id}-drop)`}>
          <path d={SPARK_OUTER} fill="#FBF9F3" />
          <path d={SPARK_INNER} fill="#FBF9F3" />
        </g>
      )}

      {badge === "doodlewire" && (
        <g filter={`url(#${id}-drop)`}>
          <path
            fillRule="evenodd"
            clipRule="evenodd"
            d={DOODLEWIRE_TOP}
            fill="#FBF9F3"
          />
          <path d={DOODLEWIRE_BOTTOM} fill="#FBF9F3" />
        </g>
      )}

      <defs>
        <Gradients id={id} />
        <Shadow
          id={`${id}-drop`}
          x={11}
          y={10}
          width={42}
          height={46}
          dy={2}
          blur={2}
        />
      </defs>
    </svg>
  );
}
