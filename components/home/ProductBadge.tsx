export function MarkPlate({ id }: { id: string }) {
  return (
    <>
      <rect
        x="0.5"
        y="0.5"
        width="62"
        height="62"
        rx="10.5"
        fill="#14120E"
        stroke={`url(#${id}-edge)`}
      />
      {DOT_STEPS.map((y) =>
        DOT_STEPS.map((x) =>
          (x === DOT_FIRST || x === DOT_LAST) &&
          (y === DOT_FIRST || y === DOT_LAST) ? null : (
            <rect
              key={`${x}-${y}`}
              x={x}
              y={y}
              width="3.25"
              height="3.25"
              fill="#3B3936"
            />
          ),
        ),
      )}
    </>
  );
}

