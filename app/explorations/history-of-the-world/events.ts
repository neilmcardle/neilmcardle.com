EVENTS.sort((a, b) => a.year - b.year);

const STOPS: [number, number][] = [
  [START, 0],
  [-10000, 0.12],
  [-3500, 0.22],
  [-800, 0.33],
  [500, 0.47],
  [1450, 0.62],
  [1750, 0.74],
  [1914, 0.86],
  [END, 1],
];

export function position(year: number) {
  const y = Math.min(END, Math.max(START, year));
  for (let i = 1; i < STOPS.length; i++) {
    const [y1, p1] = STOPS[i];
    if (y <= y1) {
      const [y0, p0] = STOPS[i - 1];
      return p0 + ((y - y0) / (y1 - y0)) * (p1 - p0);
    }
  }
  return 1;
}

export function yearAt(p: number) {
  const q = Math.min(1, Math.max(0, p));
  for (let i = 1; i < STOPS.length; i++) {
    const [y1, p1] = STOPS[i];
    if (q <= p1) {
      const [y0, p0] = STOPS[i - 1];
      return y0 + ((q - p0) / (p1 - p0)) * (y1 - y0);
    }
  }
  return END;
}

export function yearLabel(year: number) {
  const y = Math.round(year);
  if (y < 0) return `${Math.abs(y).toLocaleString("en-GB")} BCE`;
  return `${y} CE`;
}

export function eraOf(year: number) {
  return ERAS.find((e) => year < e.to) ?? ERAS[ERAS.length - 1];
}
